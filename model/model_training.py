def train_local(global_weights, X_train, y_train, epochs=3, lr=0.001):
    """
    Train a local LSTM on client data.
    Returns updated model weights (never shares raw data).
    """
    model = get_model()
    model.load_state_dict(copy.deepcopy(global_weights))
    model.train()

    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    criterion = nn.MSELoss()
    loader    = get_dataloader(X_train, y_train)

    epoch_losses = []
    for epoch in range(epochs):
        total_loss = 0
        for X_batch, y_batch in loader:
            X_batch = X_batch.to(device)
            y_batch = y_batch.to(device)
            optimizer.zero_grad()
            pred = model(X_batch)
            loss = criterion(pred, y_batch)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            total_loss += loss.item()
        epoch_losses.append(total_loss / len(loader))

    return model.state_dict(), epoch_losses

def proof_of_learning(weights, X_val, y_val, epsilon=1e-6):
    """
    Evaluate model on global validation set
    Returns quality score (0-100)
    """
    model = get_model()
    model.load_state_dict(weights)
    model.eval()

    loader = get_dataloader(X_val, y_val, shuffle=False)
    preds, targets = [], []

    with torch.no_grad():
        for X_batch, y_batch in loader:
            p = model(X_batch.to(device)).cpu().numpy()
            preds.extend(p)
            targets.extend(y_batch.numpy())

    mse = mean_squared_error(targets, preds)
    return mse, 1.0 / (mse + epsilon)

def federated_average(weight_list, alpha_list):
    """
    Weighted FedAvg
    alpha_list: softmax governance weights
    """
    avg_weights = copy.deepcopy(weight_list[0])
    for key in avg_weights:
        avg_weights[key] = torch.zeros_like(avg_weights[key], dtype=torch.float32)
        for weights, alpha in zip(weight_list, alpha_list):
            avg_weights[key] += alpha * weights[key].float()
    return avg_weights

def softmax_weights(scores):
    """Equation (4) from the paper."""
    scores = np.array(scores, dtype=float)
    e      = np.exp(scores - np.max(scores))
    return e / e.sum()

def normalize_scores(raw_scores, threshold=10):
    """Normalize raw quality scores to 0-100 for the blockchain."""
    arr     = np.array(raw_scores)
    min_s   = arr.min()
    max_s   = arr.max()
    normed  = ((arr - min_s) / (max_s - min_s + 1e-9)) * 100
    return [max(0, int(s)) for s in normed]

