def add_technical_features(df):
    """Add multiple stock features for richer input."""
    df = df.copy()
    # Normalize volume
    df["Volume"] = df["Volume"] / df["Volume"].max()
    # Price-based features (returns)
    df["Close_ret"] = df["Close"].pct_change()
    df["High_ret"]  = df["High"].pct_change()
    df["Low_ret"]   = df["Low"].pct_change()
    df["Open_ret"]  = df["Open"].pct_change()
    df.dropna(inplace=True)
    return df

def make_sequences(df, seq_len=SEQ_LEN):
    """Convert time series into (X, y) sequences for LSTM."""
    feature_cols = ["Close_ret", "Open_ret", "High_ret", "Low_ret", "Volume"]
    data = df[feature_cols].values

    scaler = MinMaxScaler()
    data   = scaler.fit_transform(data)

    X, y = [], []
    for i in range(seq_len, len(data)):
        X.append(data[i - seq_len:i])       # shape: (seq_len, n_features)
        y.append(data[i, 0])                # predict next Close_ret

    X = np.array(X, dtype=np.float32)
    y = np.array(y, dtype=np.float32)

    # Train / Val / Test split: 70 / 15 / 15
    n       = len(X)
    t_end   = int(n * 0.70)
    v_end   = int(n * 0.85)

    return {
        "X_train": X[:t_end],   "y_train": y[:t_end],
        "X_val":   X[t_end:v_end], "y_val": y[t_end:v_end],
        "X_test":  X[v_end:],   "y_test":  y[v_end:],
        "scaler":  scaler,
        "raw_close": df["Close"].values[seq_len:]
    }

